async function feedbackChecks(page){
 const check=(condition,message)=>{if(!condition)throw Error(message);};
 const browser=page.context().browser(),context=await browser.newContext({viewport:{width:1440,height:1000}});
 const errors=[];
 const tab=await context.newPage();tab.on('pageerror',e=>errors.push(e.message));
 await tab.goto('http://127.0.0.1:4183/#classes');
 const fixture=await tab.evaluate(()=>{
  const D=window.HEXA_DATA,E=window.HexaEngine;
  const ren=E.defaults(D.classes.find(c=>c.id==='ren')),adele=E.defaults(D.classes.find(c=>c.id==='adele'));
  ren.levels.masteryCore1=19;adele.levels.masteryCore1=7;
  const stored={selected:'ren',settings:E.settings(),drafts:{ren,adele,bishop:null,hero:[]}};
  localStorage.setItem('hexa-planner-v1',JSON.stringify(stored));
  return {adele};
 });
 await tab.reload();
 check(await tab.locator('#saved-class-count').innerText()==='2','Only valid saved classes should load');
 await tab.locator('#class-gallery a[href="#class=ren"]').click();
 await tab.locator('#matrix-node-level-masteryCore1').waitFor();
 const edit=async(selector,text,expected=text)=>{
  const input=tab.locator(selector);
  await input.click();
  await tab.evaluate(selector=>{
   window.field=document.querySelector(selector);window.refocuses=0;
   window.countFocus=e=>{if(e.target===window.field)window.refocuses++;};
   document.addEventListener('focusin',window.countFocus);
  },selector);
  await input.press('ControlOrMeta+A');
  await input.pressSequentially(text,{delay:90});
  check(await input.inputValue()===expected,selector+' accepts '+text+' as '+expected);
  const stable=await tab.evaluate(()=>{
   document.removeEventListener('focusin',window.countFocus);
   return window.refocuses===0&&window.field===document.activeElement&&window.field.isConnected;
  });
  check(stable,selector+' keeps the original input focused');
  await input.press('Enter');
 };
 await edit('#matrix-node-level-masteryCore1','25');
 await edit('#matrix-node-level-masteryCore1','05','5');
 await edit('#matrix-node-level-masteryCore1','35','30');
 await edit('#matrix-node-level-masteryCore1','19');
 await tab.locator('[data-matrix-core="masteryCore1"]').click();
 await edit('#matrix-current-level','25');
 await edit('#matrix-current-level','19');
 await edit('#matrix-goal-level','25');
 await tab.locator('.bulk-levels summary').click();
 await edit('#bulk-level-masteryCore1','23');
 await edit('#bulk-goal-masteryCore1','29');
 await edit('#matrix-node-level-generalCore1','25');
 await edit('#owned-fragments','1500');
 await edit('#owned-erda','20');
 const input=tab.locator('#matrix-node-level-masteryCore1');
 await input.click();await input.fill('25');
 await input.press('Home');await input.press('Delete');await input.pressSequentially('1');
 check(await input.inputValue()==='15','Editing in the middle preserves caret position');
 await input.fill('0029');
 check(await input.inputValue()==='29','Pasted leading zeroes are removed');
 await input.press('Enter');
 await tab.reload();
 check(await tab.locator('#matrix-node-level-masteryCore1').inputValue()==='29','Typed levels persist');
 check(await tab.locator('#owned-fragments').inputValue()==='1500','Material balances persist');
 await tab.locator('.workspace-link').click();
 check(await tab.locator('[data-remove-class]').count()===2,'Each saved card has a Remove button');
 await tab.locator('[data-remove-class="ren"]').click();
 check(await tab.locator('#dialog').isVisible(),'Remove asks which saved class will be deleted');
 await tab.locator('#dialog [data-action="close"]').click();
 check(await tab.locator('[data-remove-class="ren"]').count()===1,'Cancel keeps the class');
 await tab.locator('[data-remove-class="ren"]').click();
 await tab.locator('[data-confirm-remove-class="ren"]').click();
 check(await tab.locator('[data-remove-class="ren"]').count()===0,'Confirmed removal updates library immediately');
 let saved=await tab.evaluate(()=>JSON.parse(localStorage.getItem('hexa-planner-v1')));
 check(!Object.hasOwn(saved.drafts,'ren'),'Removed class is deleted from storage');
 check(JSON.stringify(saved.drafts.adele)===JSON.stringify(fixture.adele),'Removing Ren preserves Adele');
 await tab.reload();
 check(await tab.locator('#saved-class-count').innerText()==='1','Removal survives reload');
 await tab.locator('[data-library-scope="all"]').click();
 await tab.locator('#class-gallery a[href="#class=ren"]').click();
 check(await tab.locator('#matrix-node-level-masteryCore1').inputValue()==='0','Removed class opens at default levels');
 await tab.locator('.workspace-link').click();
 check(await tab.locator('#saved-class-count').innerText()==='1','Browsing a class alone does not save it');
 await tab.locator('[data-remove-class="adele"]').click();
 await tab.locator('[data-confirm-remove-class="adele"]').click();
 check(await tab.locator('.gallery-empty').isVisible(),'Removing the last class shows an empty state');

 const restricted=await context.newPage();restricted.on('pageerror',e=>errors.push(e.message));
 await restricted.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:4183/')?route.continue():route.abort());
 await restricted.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Storage access denied','SecurityError');}}));
 await restricted.goto('http://127.0.0.1:4183/#class=ren');
 const restrictedInput=restricted.locator('#matrix-node-level-masteryCore1');
 await restrictedInput.click();await restrictedInput.pressSequentially('25',{delay:90});
 check(await restrictedInput.inputValue()==='25','Number editing works when storage and third-party requests are blocked');
 check(await restricted.locator('#saved-status[data-storage-unavailable]').isVisible(),'Storage limitation is explained');
 await restricted.locator('.workspace-link').click();
 check(await restricted.locator('[data-remove-class="ren"]').count()===1,'In-memory progress is available');
 await restricted.close();
 await context.close();

 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
 await phone.goto('http://127.0.0.1:4183/#class=ren');
 const phoneField=phone.locator('#matrix-node-level-masteryCore1');
 await phoneField.tap();await phoneField.pressSequentially('25',{delay:120});
 check(await phoneField.inputValue()==='25','Touch-input flow accepts two digits');
 check(await phoneField.evaluate(el=>el===document.activeElement),'Touch input retains focus');
 await phone.locator('.planner-back').tap();
 await phone.locator('[data-remove-class="ren"]').waitFor();
 check(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile class cards fit viewport');
 const button=await phone.locator('[data-remove-class="ren"]').boundingBox();
 check(button.height>=44,'Remove has a touch-sized target');
 await phone.screenshot({path:'output/playwright/feedback-mobile.png',animations:'disabled'});
 await phone.locator('[data-remove-class="ren"]').tap();
 await phone.screenshot({path:'output/playwright/feedback-confirm-mobile.png',animations:'disabled'});
 await phone.locator('[data-confirm-remove-class="ren"]').tap();
 check(await phone.locator('#saved-class-count').innerText()==='0','Touch removal works');
 await mobile.close();
 check(errors.length===0,'No browser exceptions: '+errors.join('; '));
 return {passed:true,checks:['stable focus across matrix, bulk, goal, Janus and material inputs','two digits, leading zeroes, paste, caret edits and persistence','invalid saved entries recovered without losing valid classes','remove, cancel, persistence, empty state and other-class preservation','blocked storage and third-party requests','390px touch input and removal'],browserErrors:errors};
}
